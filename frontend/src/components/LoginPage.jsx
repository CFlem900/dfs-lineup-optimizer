export default function LoginPage() {
  const { providers, login } = useAuth()

  const params = new URLSearchParams(window.location.search)
  const authError = params.get('auth_error')

  return (
    <div className="min-h-screen bg-ticker-bg flex items-center justify-center p-4">
      <div className="w-full max-w-sm">
        {/* Logo + Title */}
        <div className="text-center mb-8">
          <Activity className="w-12 h-12 text-ticker-green mx-auto mb-3" />
          <h1 className="text-2xl font-bold">
            <span className="text-ticker-green">Rotation</span>
            <span className="text-white">Engine</span>
          </h1>
          <p className="text-sm text-ticker-muted mt-2">
            Sign in to access projections
          </p>
        </div>

        {/* Login Card */}
        <div className="bg-ticker-card border border-ticker-border rounded-xl p-6 space-y-3">
          {authError && (
            <div className="p-3 bg-red-900/20 border border-red-800/50 rounded-lg text-sm text-red-300 text-center mb-2">
              Login failed. Please try again.
            </div>
          )}

          {providers.length === 0 && (
            <p className="text-sm text-ticker-muted text-center py-4">
              No login providers configured.
            </p>
          )}

          {providers.map((provider) => {
            const meta = PROVIDER_META[provider] || {
              label: provider,
              bg: 'bg-gray-700 hover:bg-gray-600',
              text: 'text-white',
              icon: null,
            }
            return (
              <button
                key={provider}
                onClick={() => login(provider)}
                className={`w-full flex items-center justify-center gap-3 px-4 py-3
                  rounded-lg font-medium text-sm transition-all
                  ${meta.bg} ${meta.text}`}
              >
                {meta.icon}
                Continue with {meta.label}
              </button>
            )
          })}
        </div>

        <p className="text-xs text-ticker-muted text-center mt-6">
          NBA DFS Lineup Optimizer
        </p>
      </div>
    </div>
  )
}
